"""Rebuild EVALUATION.md and the LaTeX tables from a run's scores, in both scoring modes.

In short: run this after any experiment run, and both the results page and the paper's LaTeX
tables update themselves. Every model is graded two ways: against a random half of each pair's
cells (team convention; the other half is a "technical duplicate" reference), and against all
of its cells. Models not run yet show "--".

    cd compositional
    python scripts/make_table.py                         # split s_shared (default)
    python scripts/make_table.py --split s_shared_val
    python scripts/make_table.py --scores a.csv b.csv    # explicit files (concatenated)

Technical details:
- Reads `results/compositional/<split>/scores.csv`: the EvalContext.score long format plus a
  `truth` column ("halves" / "all"; missing = "halves") and Experiment 2's `residual_pearson` rows.
- Writes:
  - `EVALUATION.md`: both modes × (all / non-additive / additive pairs);
  - `tables/composition_results.tex` (halves, the paper's main table);
  - `tables/composition_results_allcells.tex`.
- Both modes use the same pair list, so their medians are comparable. The all-cells tables add
  a "wMSE Δ (all − halves)" column.
"""

import argparse
from datetime import date
from pathlib import Path

import pandas as pd

from stack_compositional.report import (
    LATEX_COLUMNS, MARKDOWN_COLUMNS, NON_ADDITIVE, REFERENCE_ROWS, ROWS, latex_table, markdown_table,
    subset_pairs, summary, with_truth,
)

HERE = Path(__file__).resolve().parents[1]  # compositional/
REPO = HERE.parent
EMPTY = pd.DataFrame(columns=["panel", "model", "perturbation", "metric", "value", "gap_closed", "truth"])
MD_ROWS = ROWS + REFERENCE_ROWS

INTRO = """# Experiment 2 — evaluation results

> Generated by `scripts/make_table.py`; do not edit by hand. Re-run it after every run.

## In short

Each row is a way of predicting what cells look like when **two** genes are perturbed at once.
Each number is the median over the held-out gene pairs (pairs no model trained on).

- **Pearson**: how closely the predicted changes in gene activity track the real ones
  (1 = perfect, 0 = no relationship). Higher is better.
- **MSE / wMSE**: the average size of the prediction error. wMSE weights the genes the
  perturbation changes most, so it focuses on what matters. Lower is better.
- **Residual Pearson**: does the model predict the part of a double perturbation's effect that is
  *not* just the sum of the two single effects (gene interaction)? Higher is better. The additive
  baseline predicts no interaction, so it has no score ("--").
- **Bold** = best model in its column. **--** = not run yet.

**Two ways of grading.** The "right answer" for a held-out pair is the average of its measured
cells. We grade every model twice:
1. **Halves (team convention, main result):** the pair's cells are split at random into two
   halves. Models are graded against the first half. The second half acts as a *repeat
   experiment* (the technical duplicate), which shows the best score achievable given
   measurement noise.
2. **All cells (robustness check):** models are graded against all of the pair's cells. This is
   less noisy, especially for small pairs, but leaves nothing over for a repeat experiment, so
   the duplicate rows show "n/a". The last column shows how much wMSE changes.

If both ways rank the models the same, the conclusion does not depend on the halving.

The **non-additive** tables matter most for our hypothesis: these are the pairs where simply
adding the two single effects works worst.

## Technical details

- Scores file(s): {sources}
- Split: `{split}` · gene panel: `{panel}` · generated {today}
- Pearson = `pearson_deltactrl`; MSE = `mse`; wMSE = `wmse` (Miller et al. DE-weighted MSE);
  Residual Pearson = corr($\\hat r_{{AB}}$, $r_{{AB}}$) on the pair's top 100 DE genes, with
  $r_{{AB}} = \\delta_{{AB}} - (\\delta_A + \\delta_B)$ (see PLAN.md).
- Halves: truth and DE from the first half (`splits/*halves*`); duplicates from the second.
  All cells: truth and DE from every cell of the pair; no duplicates. The model inputs (singles,
  controls) are the same in both.
- Model names in the scores file: {models}.
- Non-additive pairs (current list, Study 4's; to be replaced by the definition in SPLITS.md): {non_additive}.
"""

TITLES = {"all": "All held-out pairs", "non-additive": "Non-additive pairs", "additive": "Additive pairs"}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--split", default="s_shared", help="folder name under results/compositional/")
    parser.add_argument("--scores", type=Path, nargs="+", default=None)
    parser.add_argument("--panel", default="stack_genes")
    parser.add_argument("--markdown", type=Path, default=HERE / "EVALUATION.md")
    parser.add_argument("--latex-dir", type=Path, default=HERE / "tables")
    args = parser.parse_args()

    sources = args.scores or [REPO / "results" / "compositional" / args.split / "scores.csv"]
    found = [with_truth(pd.read_csv(p)) for p in sources if p.exists()]
    long = pd.concat(found, ignore_index=True) if found else EMPTY
    for p in sources:
        print(("read    " if p.exists() else "missing ") + str(p))

    pairs = sorted(set(long.loc[long["panel"] == args.panel, "perturbation"]))
    parts = [INTRO.format(
        sources=", ".join(f"`{p.relative_to(REPO) if p.is_relative_to(REPO) else p}`" for p in sources),
        split=args.split, panel=args.panel, today=date.today().isoformat(),
        models=", ".join(f"{label} = `{model}`" for label, model in MD_ROWS),
        non_additive=", ".join(NON_ADDITIVE),
    )]
    for truth, heading in [("halves", "Graded against half of the cells (main)"),
                           ("all", "Graded against all cells (robustness check)")]:
        parts.append(f"# {heading}\n")
        for subset, title in TITLES.items():
            n = len(subset_pairs(pairs, subset))
            table = summary(long, args.panel, MARKDOWN_COLUMNS, subset, truth, rows=MD_ROWS, pairs=pairs)
            extra = None
            if truth == "all":
                halves = summary(long, args.panel, MARKDOWN_COLUMNS, subset, "halves", rows=MD_ROWS, pairs=pairs)
                extra = table["wMSE"] - halves["wMSE"]
            parts.append(f"## {title} ({n}), {'halves' if truth == 'halves' else 'all cells'}\n\n"
                         + markdown_table(table, extra=extra, extra_label="wMSE Δ (all − halves)",
                                          refs_unavailable=truth == "all") + "\n")

    args.markdown.write_text("\n".join(parts))
    args.latex_dir.mkdir(parents=True, exist_ok=True)
    for truth, name in [("halves", "composition_results.tex"), ("all", "composition_results_allcells.tex")]:
        table = summary(long, args.panel, LATEX_COLUMNS, "all", truth, pairs=pairs)
        (args.latex_dir / name).write_text(latex_table(table, truth=truth))
        print(f"wrote   {args.latex_dir / name}")
    print(f"wrote   {args.markdown}")


if __name__ == "__main__":
    main()
